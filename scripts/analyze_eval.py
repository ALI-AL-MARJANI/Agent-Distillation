"""Results tables and error analysis, computed from the per-question evaluation files.

python scripts/analyze_eval.py      # ~1 s
-> results/tables.md, results/error_analysis.md, results/eval/breakdown.json

- held-out split into h01-h10 (written with the original agent) and h11-h30 (written with the training templates)
- dev vs held-out: is the gap explained by how close the questions are to the training questions?
- error analysis: the manual labels in results/error_labels.yaml, counted, with the code of each failure
"""

from __future__ import annotations

from collections import Counter

import numpy as np

from distill.metrics import fisher_exact
from distill.overlap import jaccard
from distill.runinfo import DATA, RESULTS, load_yaml, read_jsonl, run_metadata, write_json

MODELS = {"student_base": "Student, before fine-tuning", "student_distilled": "Student, distilled",
          "teacher": "Teacher"}  # fmt: skip
GROUPS = ("dev", "h01-h10", "h11-h30")


def group(qid: str) -> str:
    return "dev" if qid.startswith("q") else ("h01-h10" if int(qid[1:]) <= 10 else "h11-h30")


def score(rows: dict, ids: list[str]) -> str:
    return f"{sum(rows[i]['correct'] for i in ids)}/{len(ids)}"


def main() -> None:
    rows = {m: {r["id"]: r for r in read_jsonl(RESULTS / f"eval/{m}_per_question.jsonl")} for m in MODELS}
    summary = {m: load_yaml(RESULTS / f"eval/{m}.json") for m in MODELS}
    questions = load_yaml(DATA / "eval/questions.yaml")
    ids = [q["id"] for q in questions]
    by_group = {g: [i for i in ids if group(i) == g] for g in GROUPS}
    heldout = by_group["h01-h10"] + by_group["h11-h30"]

    # closeness of each eval question to the training set (train split only)
    train = [q["question"] for q in read_jsonl(DATA / "train/questions.jsonl") if q["split"] == "train"]
    closest = {q["id"]: max(jaccard(q["question"], t) for t in train) for q in questions}
    ranked = sorted(ids, key=closest.get)
    thirds = {"least similar": ranked[:17], "middle": ranked[17:34], "most similar": ranked[34:]}

    stud, teach = rows["student_distilled"], rows["teacher"]

    def right(rs, part):
        return sum(rs[i]["correct"] for i in part)

    tests = {
        "student_dev_vs_heldout": fisher_exact(
            right(stud, by_group["dev"]), 20 - right(stud, by_group["dev"]),
            right(stud, heldout), 30 - right(stud, heldout)),
        "student_h01_10_vs_h11_30": fisher_exact(
            right(stud, by_group["h01-h10"]), 10 - right(stud, by_group["h01-h10"]),
            right(stud, by_group["h11-h30"]), 20 - right(stud, by_group["h11-h30"])),
    }  # fmt: skip

    # --- tables.md
    lines = ["# Results", "", "Generated by `scripts/analyze_eval.py` from `results/eval/*`. 50 frozen questions, same agent "
             "and sandbox, Ollama 0.18.2, Q4_K_M for all three models, temperature 0, seed 0, one run each.", "",
             "| Model | Accuracy (50) | dev (20) | held-out (30) | Avg retries | Latency p50 | Memory (loaded) |",
             "|---|---:|---:|---:|---:|---:|---:|"]  # fmt: skip
    for m, name in MODELS.items():
        s, o = summary[m]["summary"], summary[m]["ollama"]
        lines.append(
            f"| {name} | {s['all']['n_correct']}/50 | {s['dev']['n_correct']}/20 | {s['heldout']['n_correct']}/30 "
            f"| {s['all']['avg_retries']:.2f} | {s['all']['latency_s_p50']:.1f} s "
            f"| {o['loaded_size_vram_bytes'] / 1e9:.2f} GB |"
        )
    lines += ["", "## Held-out split: original (h01-h10) vs new (h11-h30)", "",
              "h11-h30 were written on the same day as the training templates, so they could be closer to them.", "",
              "| Model | dev (20) | h01-h10 (10) | h11-h30 (20) |", "|---|---:|---:|---:|"]  # fmt: skip
    for m, name in MODELS.items():
        lines.append(f"| {name} | " + " | ".join(score(rows[m], by_group[g]) for g in GROUPS) + " |")
    lines += ["", f"Fisher exact test, distilled student, h01-h10 vs h11-h30: p = {tests['student_h01_10_vs_h11_30']:.2f}.",
              "", "## Dev vs held-out gap", "",
              "Closest training question per eval question (word Jaccard), and the distilled student's accuracy:", "",
              "| Questions | mean closest Jaccard | student | teacher |", "|---|---:|---:|---:|"]  # fmt: skip
    for g in GROUPS:
        part = by_group[g]
        lines.append(
            f"| {g} | {np.mean([closest[i] for i in part]):.3f} | {score(stud, part)} | {score(teach, part)} |"
        )
    for name, part in thirds.items():
        rng = f"{closest[part[0]]:.2f}-{closest[part[-1]]:.2f}"
        lines.append(f"| {name} third ({rng}) | | {score(stud, part)} | {score(teach, part)} |")
    teacher_right = {g: [i for i in by_group[g] if teach[i]["correct"]] for g in GROUPS}
    lines += ["", "On the questions the teacher gets right, the student gets: "
              + ", ".join(f"{g} {score(stud, teacher_right[g])}" for g in GROUPS) + ".",
              f"Fisher exact test, distilled student, dev vs held-out: p = {tests['student_dev_vs_heldout']:.2f}."]  # fmt: skip
    (RESULTS / "tables.md").write_text("\n".join(lines) + "\n")

    # --- error_analysis.md
    labels = load_yaml(RESULTS / "error_labels.yaml")
    failed = [i for i in ids if not stud[i]["correct"]]
    assert set(failed) == set(labels["labels"]), "every failure needs exactly one label"
    counts = Counter(v["category"] for v in labels["labels"].values())
    out = ["# Error analysis: distilled student", "",
           f"{len(failed)} failures out of 50 (`results/eval/student_distilled_per_question.jsonl`), labelled by hand in "
           "`results/error_labels.yaml`. \"Teacher too\" = the teacher also fails this question.", ""]  # fmt: skip
    for cat, desc in labels["categories"].items():
        out += [f"## {desc} ({counts[cat]})", ""]
        for qid, lab in labels["labels"].items():
            if lab["category"] != cat:
                continue
            r = stud[qid]
            too = " (teacher too)" if not teach[qid]["correct"] else ""
            out += [f"- **{qid}**{too}: {r['question']}", f"  {lab['note']}. Expected `{r['truth']}`."]
        out.append("")
    shared = [i for i in failed if not teach[i]["correct"]]
    out.append(f"Failures shared with the teacher: {len(shared)} of {len(failed)} ({', '.join(shared)}).")
    (RESULTS / "error_analysis.md").write_text("\n".join(out) + "\n")

    write_json(
        RESULTS / "eval/breakdown.json",
        {
            **run_metadata(),
            "by_group": {m: {g: score(rows[m], by_group[g]) for g in GROUPS} for m in MODELS},
            "closest_train_jaccard": closest,
            "fisher_p": tests,
            "error_categories": dict(counts),
            "failures_shared_with_teacher": shared,
        },
    )
    print("\n".join(lines))


if __name__ == "__main__":
    main()
